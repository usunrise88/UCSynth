// numfmt — форматирование чисел для OLED-попапов.
//
// Вынесено из display.cpp отдельным header-only файлом сознательно: display.cpp тянет драйвер I2C и
// на хосте не собирается, а формат значений хочется проверять тестом. Здесь только <cmath>/<cstdio>.
#pragma once

#include <cmath>
#include <cstddef>
#include <cstdio>

// Записать v как «-0.50» / «0.00» / «12.34» (две цифры после точки).
//
// Знак форматируется ОТДЕЛЬНО от модуля. Наивный вариант — `(int)v` для целой части и "%d" —
// теряет минус для −1 < v < 0: усечение к нулю даёт 0, а "%d" печатает «0», так что flt_env_amt
// = −0.5 показывался как «0.49» (и округление +0.5f, применённое к отрицательной дроби, занижало
// её ещё на счёт). При v = −1.0 всё выглядело правильно, поэтому баг читался как случайный глюк.
inline void fmt_float_2dp(char *out, size_t n, float v)
{
    const float a = std::fabs(v);
    int whole = (int)a;
    int frac  = (int)((a - (float)whole) * 100.0f + 0.5f);
    if (frac > 99) { frac -= 100; ++whole; }   // 0.999 → «1.00», а не «0.100»
    std::snprintf(out, n, "%s%d.%02d", v < 0.0f ? "-" : "", whole, frac);
}
